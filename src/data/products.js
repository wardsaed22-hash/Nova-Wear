/* ---------- Helpers ---------- */

export const getProductBySlug = (slug) => products.find((p) => p.slug === slug);
export const getCategory = (slug) => categories.find((c) => c.slug === slug);
export const getCollection = (slug) => collections.find((c) => c.slug === slug);

export const newArrivals = () =>
  products.filter((p) => p.newArrival).sort((a, b) => b.addedAt.localeCompare(a.addedAt));
export const bestSellers = () => products.filter((p) => p.bestSeller);
export const featured = () => products.filter((p) => p.featured);

export function getRelated(product, limit = 4) {
  const sameCat = products.filter((p) => p.id !== product.id && p.category === product.category);
  const sameCol = products.filter(
    (p) => p.id !== product.id && p.collection === product.collection && p.category !== product.category,
  );
  return [...sameCat, ...sameCol].slice(0, limit);
}

/** Free-text search over name, category, collection and colour. */
export function searchProducts(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const terms = q.split(/\s+/);
  return products.filter((p) => {
    const haystack = [
      p.name,
      getCategory(p.category)?.name,
      getCollection(p.collection)?.name,
      p.colors.map((c) => c.name).join(' '),
    ]
      .join(' ')
      .toLowerCase();
    return terms.every((t) => haystack.includes(t));
  });
}

